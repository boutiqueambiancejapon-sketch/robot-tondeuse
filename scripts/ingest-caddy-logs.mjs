#!/usr/bin/env node
// Owner dashboard: reads Caddy's access log (JSON, in journald) and stores it in analytics.hits.
// Ported from 10minlanguages.com (itself adapted from Toutou Gourmet). Run every minute by
// deploy/qrt-ingest.timer; resumes from the
// journald cursor saved in analytics.ingest_state (first run: last 7 days).
// Humans: pages, /go/ redirections and PDF guides (no static files, share images, /api, /dashboard,
// /admin), no IP or User-Agent, a visitor
// hash salted per day (analytics.visitor_salt, salt deleted after 2 days). Bots: every request,
// with IP and User-Agent (to spot fake bots). Everyone: country code (local DB-IP file), the human
// address is read for it, then forgotten.
// Scraper filter (2026-11-21, from Toutou via 10minlanguages): a "person" with no Accept-Language, a headless browser
// or a Chrome older than 100 is stored as kind 'scraper' (out of every people count); so is a visitor hash with more
// than 30 page views in one hour (second pass after each run). --reclass-history applies the first rules to the hits
// already stored (journal read again from the first day), then prints the counts.
// Usage: DATABASE_URL=postgresql:///qrt?host=/var/run/postgresql INGEST_HOSTS=quel-robot-tondeuse.com node scripts/ingest-caddy-logs.mjs [--dry] [--reclass-history]

import { createHash, randomBytes } from 'node:crypto'
import { spawn } from 'node:child_process'
import readline from 'node:readline'
import pg from 'pg'
import { aiReferrer, classifyUa, deviceOf } from './lib/bots.mjs'
import { countryOf } from './lib/geo.mjs'
import { buildStaticList, findFingerprint, isStaticIgnored, visitorKey } from './lib/analytics-ignore.mjs'

const DRY = process.argv.includes('--dry')
const HISTORY = process.argv.includes('--reclass-history')
const HOSTS = (process.env.INGEST_HOSTS || '').split(',').map((h) => h.trim().toLowerCase()).filter(Boolean)
const SOURCE = 'caddy-journal'
const BATCH = 500
const RETENTION_DAYS = 180
const STATIC = /^\/(_next\/|images\/|fonts\/|favicon|icons?\/|apple-touch|manifest|robots\.txt$|sitemap)|\.(js|css|map|png|jpe?g|webp|avif|gif|svg|ico|woff2?|txt|xml|json|mp4|webm)$/i
// Not pages: share images and icons generated by Next.js (/blog/x/opengraph-image-ab12cd), service
// worker, manifest, JSON, robots, sitemaps. Same list as lib/dashboard/assets.ts, except the PDF
// guides (/guides/*.pdf), kept as a download goal and left out of page views by the queries.
const ASSET = /((^|\/)(opengraph-image|twitter-image)(-[a-z0-9]+)?(\.[a-z0-9]+)?$|(^|\/)(apple-)?icon[0-9]*(-[a-z0-9]+)?(\.[a-z0-9]+)?$|\/sw\.js$|\.(webmanifest|json|xml|txt)$|^\/(_next|api)\/|^\/(robots\.txt|manifest|sitemap))/i
const PRIVATE = /^\/(dashboard|api|admin)(\/|$)/
// The last 20 s of the journal wait for the next run, so the owner's address can be recorded first.
const SETTLE_DELAY = '-20s'

if (!HOSTS.length) { console.error('[ingest] INGEST_HOSTS missing'); process.exit(1) }
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL || 'postgresql:///qrt?host=/var/run/postgresql', max: 2 })

const STATIC_IGNORED = buildStaticList()
let ownerRows = []
const ownerSeen = new Map()
const salts = new Map()

function isOwnerIp(ip) {
  const key = visitorKey(ip)
  if (!key) return false
  if (!ownerSeen.has(key)) ownerSeen.set(key, findFingerprint(ownerRows, ip) !== null)
  return ownerSeen.get(key)
}

async function loadOwnerRows() {
  if (!DRY) await pool.query('DELETE FROM analytics.ignored_ips WHERE expires_at <= now()')
  ownerRows = (await pool.query('SELECT salt, hash FROM analytics.ignored_ips WHERE expires_at > now()')).rows
}

/** Salt of a UTC day, created on first use. Kept 2 days, then deleted (hashes become unlinkable). */
async function saltOf(day) {
  if (salts.has(day)) return salts.get(day)
  const fresh = randomBytes(32).toString('hex')
  const { rows } = await pool.query(
    `INSERT INTO analytics.visitor_salt (day, salt) VALUES ($1, $2)
     ON CONFLICT (day) DO UPDATE SET day = EXCLUDED.day RETURNING salt`,
    [day, fresh],
  )
  salts.set(day, rows[0].salt)
  return rows[0].salt
}

function header(h, name) {
  const v = h?.[name] ?? h?.[name.toLowerCase()]
  return Array.isArray(v) ? v[0] : v
}

function hostOf(url) {
  if (!url) return null
  try { return new URL(url).hostname.replace(/^www\./, '') } catch { return null }
}

function pathOf(url) {
  try { return new URL(url).pathname.slice(0, 120) } catch { return null }
}

function queryParam(uri, name, max) {
  const q = uri.indexOf('?')
  if (q < 0) return null
  const v = new URLSearchParams(uri.slice(q + 1)).get(name)
  return v ? v.trim().toLowerCase().slice(0, max) : null
}

/** Scraper posing as a browser: real browsers always send Accept-Language; headless or very old Chrome is a robot. */
export function scraperReason(headers, ua) {
  if (!header(headers, 'Accept-Language')) return 'sans langue'
  if (/HeadlessChrome|PhantomJS|Electron\//.test(ua)) return 'navigateur sans tête'
  const chrome = /Chrome\/(\d+)\./.exec(ua)
  if (chrome && Number(chrome[1]) < 100) return 'navigateur périmé'
  return null
}

/** Second pass: more than 30 people page views in one hour for one visitor hash (from $1). */
export const CADENCE_SQL = `UPDATE analytics.hits SET kind = 'scraper', bot = 'cadence'
  WHERE kind = 'human' AND ts >= $1 AND (visitor, date_trunc('hour', ts)) IN (
    SELECT visitor, date_trunc('hour', ts) FROM analytics.hits
     WHERE kind IN ('human', 'scraper') AND ts >= $1 AND visitor IS NOT NULL GROUP BY 1, 2 HAVING count(*) > 30)`

/** One Caddy log line → one analytics.hits row (visitor still to hash), or null. */
function toHit(entry) {
  const req = entry.request
  if (!req || !String(entry.logger || '').startsWith('http.log.access')) return null
  const host = String(req.host || '').toLowerCase().split(':')[0]
  if (!HOSTS.includes(host)) return null
  const clientIp = req.client_ip || req.remote_ip || null
  if (isStaticIgnored(clientIp, STATIC_IGNORED)) return null
  const uri = req.uri || '/'
  const path = uri.split('?')[0].slice(0, 300)
  const ua = header(req.headers, 'User-Agent') || ''
  let { kind, bot, operator } = classifyUa(ua)
  if (kind === 'human' && req.method === 'GET') {
    const reason = scraperReason(req.headers, ua)
    if (reason) { kind = 'scraper'; bot = reason }
  }
  if (kind === 'human' || kind === 'scraper') {
    if (STATIC.test(path) || ASSET.test(path) || PRIVATE.test(path) || req.method !== 'GET') return null
    // Next.js prefetches (menu links loaded in the background) are not visits.
    const prefetch = header(req.headers, 'RSC') || header(req.headers, 'Next-Router-Prefetch') ||
      /prefetch/i.test(header(req.headers, 'Sec-Purpose') || header(req.headers, 'Purpose') || '') || /[?&]_rsc=/.test(uri)
    if (prefetch || isOwnerIp(clientIp)) return null
  }
  const referer = header(req.headers, 'Referer')
  const refHost = hostOf(referer)
  const own = refHost === host.replace(/^www\./, '')
  const human = kind === 'human' || kind === 'scraper'
  return {
    ts: new Date(entry.ts * 1000).toISOString(),
    host: host.slice(0, 100),
    method: (req.method || '').slice(0, 10),
    path,
    status: entry.status ?? 0,
    bytes: entry.size ?? null,
    duration_ms: entry.duration != null ? Math.round(entry.duration * 1000) : null,
    kind, bot, operator,
    device: human ? deviceOf(ua) : null,
    ref_host: refHost && !own ? refHost.slice(0, 100) : null,
    // Previous page when it is on the site (path only); campaign tags of the landing URL, nothing else.
    ref_path: human && own ? pathOf(referer) : null,
    utm_source: human ? queryParam(uri, 'utm_source', 60) ?? queryParam(uri, 'ref', 60) : null,
    utm_medium: human ? queryParam(uri, 'utm_medium', 30) : null,
    ref_ai: human ? aiReferrer(refHost, uri) : null,
    visitor: human ? { key: visitorKey(clientIp), ua } : null,
    // Scrapers are robots: address and User-Agent kept, like the other bots, to spot them again.
    ip: kind === 'human' ? null : clientIp,
    ua: kind === 'human' ? null : ua.slice(0, 300),
    country: countryOf(clientIp),
  }
}

async function hashVisitor(hit) {
  if (!hit.visitor) return null
  const salt = DRY ? 'dry' : await saltOf(hit.ts.slice(0, 10))
  return createHash('sha256').update(`${salt}|${hit.visitor.key}|${hit.visitor.ua}`).digest('hex').slice(0, 16)
}

const COLS = ['ts', 'host', 'method', 'path', 'status', 'bytes', 'duration_ms', 'kind', 'bot', 'operator', 'device', 'ref_host', 'ref_ai', 'ref_path', 'utm_source', 'utm_medium', 'visitor', 'ip', 'ua', 'country']

async function flush(rows, cursor) {
  for (const r of rows) r.visitor = await hashVisitor(r)
  if (DRY) { for (const r of rows.slice(0, 5)) console.log(r); return }
  const client = await pool.connect()
  try {
    await client.query('BEGIN')
    if (rows.length) {
      const values = []
      const tuples = rows.map((_, i) => `(${COLS.map((__, j) => `$${i * COLS.length + j + 1}`).join(',')})`)
      for (const r of rows) for (const c of COLS) values.push(r[c])
      await client.query(`INSERT INTO analytics.hits (${COLS.join(',')}) VALUES ${tuples.join(',')}`, values)
    }
    if (cursor) {
      await client.query(
        `INSERT INTO analytics.ingest_state (source, cursor, updated_at) VALUES ($1, $2, now())
         ON CONFLICT (source) DO UPDATE SET cursor = EXCLUDED.cursor, updated_at = now()`,
        [SOURCE, cursor],
      )
    }
    await client.query('COMMIT')
  } catch (err) {
    await client.query('ROLLBACK')
    throw err
  } finally {
    client.release()
  }
}

/** One-off: the first rules applied to the people page views already stored (the journal is read again). */
async function reclassHistory() {
  const { rows } = await pool.query(`SELECT min(ts) AS first FROM analytics.hits WHERE kind = 'human'`)
  if (!rows[0]?.first) return
  const since = new Date(rows[0].first.getTime() - 60_000).toISOString().replace('T', ' ').slice(0, 19)
  const jc = spawn('journalctl', ['-u', 'caddy', '-o', 'json', '--no-pager', '--since', since, '--utc'], { stdio: ['ignore', 'pipe', 'inherit'] })
  const rl = readline.createInterface({ input: jc.stdout })
  const found = new Map()
  for await (const line of rl) {
    let rec
    try { rec = JSON.parse(line) } catch { continue }
    const msg = typeof rec.MESSAGE === 'string' ? rec.MESSAGE : ''
    if (!msg.startsWith('{')) continue
    let entry
    try { entry = JSON.parse(msg) } catch { continue }
    const req = entry.request
    if (!req || req.method !== 'GET' || !HOSTS.includes(String(req.host || '').toLowerCase().split(':')[0])) continue
    const ua = header(req.headers, 'User-Agent') || ''
    if (classifyUa(ua).kind !== 'human') continue
    const reason = scraperReason(req.headers, ua)
    if (reason) found.set(`${new Date(entry.ts * 1000).toISOString()}|${(req.uri || '/').split('?')[0].slice(0, 300)}`, { reason, ip: req.client_ip || req.remote_ip || null, ua: ua.slice(0, 300) })
  }
  const before = (await pool.query(`SELECT count(*)::int AS n FROM analytics.hits WHERE kind = 'human'`)).rows[0].n
  let changed = 0
  if (!DRY) {
    for (const [key, v] of found) {
      const [ts, path] = key.split('|')
      const r = await pool.query(`UPDATE analytics.hits SET kind = 'scraper', bot = $3, ip = $4, ua = $5 WHERE kind = 'human' AND ts = $1 AND path = $2`, [ts, path, v.reason, v.ip, v.ua])
      changed += r.rowCount ?? 0
    }
    const c = await pool.query(CADENCE_SQL, [rows[0].first.toISOString()])
    changed += c.rowCount ?? 0
    console.log(`[ingest] history: ${c.rowCount ?? 0} by cadence`)
  }
  const byReason = {}
  for (const v of found.values()) byReason[v.reason] = (byReason[v.reason] ?? 0) + 1
  console.log(`[ingest] history: ${before} people page views before, ${changed} reclassified as scrapers${DRY ? ' (dry run)' : ''}`, byReason)
}

async function main() {
  if (HISTORY) return reclassHistory()
  const { rows } = await pool.query('SELECT cursor FROM analytics.ingest_state WHERE source = $1', [SOURCE])
  const cursor = rows[0]?.cursor
  await loadOwnerRows()
  const args = ['-u', 'caddy', '-o', 'json', '--no-pager', '--until', SETTLE_DELAY, ...(cursor ? ['--after-cursor', cursor] : ['--since', '-7d'])]
  const jc = spawn('journalctl', args, { stdio: ['ignore', 'pipe', 'inherit'] })
  const rl = readline.createInterface({ input: jc.stdout })

  let batch = []
  let lastCursor = null
  let seen = 0
  let kept = 0
  for await (const line of rl) {
    let rec
    try { rec = JSON.parse(line) } catch { continue }
    lastCursor = rec.__CURSOR || lastCursor
    seen++
    const msg = typeof rec.MESSAGE === 'string' ? rec.MESSAGE : ''
    if (!msg.startsWith('{')) continue
    let entry
    try { entry = JSON.parse(msg) } catch { continue }
    const hit = toHit(entry)
    if (hit) { batch.push(hit); kept++ }
    if (batch.length >= BATCH) { await flush(batch, lastCursor); batch = [] }
  }
  await flush(batch, lastCursor)
  const code = await new Promise((res) => jc.on('close', res))
  if (code !== 0 && seen === 0) throw new Error(`journalctl failed (code ${code}): journal read permission?`)

  if (!DRY) {
    const re = await pool.query(CADENCE_SQL, [new Date(Date.now() - 2 * 3600_000).toISOString()])
    if (re.rowCount) console.log(`[ingest] ${re.rowCount} page views reclassified as scrapers (cadence)`)
    await pool.query(`DELETE FROM analytics.hits WHERE ts < now() - interval '${RETENTION_DAYS} days'`)
    await pool.query(`DELETE FROM analytics.events WHERE ts < now() - interval '400 days'`)
    await pool.query(`DELETE FROM analytics.visitor_salt WHERE day < (now() AT TIME ZONE 'UTC')::date - 1`)
  }
  console.log(`[ingest] ${seen} lines read, ${kept} kept${DRY ? ' (dry run, nothing written)' : ''}`)
}

main().catch((err) => { console.error('[ingest]', err.message); process.exitCode = 1 }).finally(() => pool.end())
